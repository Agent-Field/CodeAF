// goldenPath holds the known-answer vectors the TypeScript client is held to (K1). It is
// regenerated only on purpose: UPDATE_VECTORS=1 go test ./internal/clientproto.
const goldenPath = "testdata/vectors.json"

type enrollCase struct {
	Name         string     `json:"name"`
	IdentityPub  string     `json:"identity_pub_hex"`
	Enrollment   Enrollment `json:"enrollment"`
	SignText     string     `json:"sign_text"`
	SignTextHex  string     `json:"sign_text_hex"`
	Valid        bool       `json:"valid"`
	WhyInvalid   string     `json:"why_invalid,omitempty"`
	SigHex       string     `json:"sig_hex"`
	DeviceIDOfSP string     `json:"device_id_of_sign_pub"`
}

type bindCase struct {
	Name       string `json:"name"`
	LinkKeyHex string `json:"link_key_hex"`
	SignPubHex string `json:"sign_pub_hex"`
	BoxPubHex  string `json:"box_pub_hex"`
	BindKeyHex string `json:"k_bind_hex"`
	MACHex     string `json:"mac_hex"`
	BindB64URL string `json:"bind_b64url"`
	Check      string `json:"check"`
	Note       string `json:"note,omitempty"`
}

func seed(b byte) []byte { return bytes.Repeat([]byte{b}, 32) }

func buildVectors(t *testing.T) map[string]any {
	t.Helper()
	identity := ed25519.NewKeyFromSeed(seed(1))
	identityPub := identity.Public().(ed25519.PublicKey)
	phone := ed25519.NewKeyFromSeed(seed(2)).Public().(ed25519.PublicKey)
	base := Enrollment{V: 1, Device: DeviceIDOf(phone), SignPub: phone, BoxPub: seed(3),
		Methods: []string{"agents.send", "agents.create", "agents.answer"}, Reads: []string{"agents.list", "agents.entries"}, Ver: 1}
	signed := base.Sign(identity)

	mk := func(name string, e Enrollment, pub ed25519.PublicKey, why string) enrollCase {
		return enrollCase{Name: name, IdentityPub: hex.EncodeToString(pub), Enrollment: e, SignText: string(e.SignText()),
			SignTextHex: hex.EncodeToString(e.SignText()), Valid: e.Verify(pub) == nil, WhyInvalid: why,
			SigHex: hex.EncodeToString(e.Sig), DeviceIDOfSP: DeviceIDOf(e.SignPub)}
	}
	reordered := signed
	reordered.Methods = []string{"agents.answer", "agents.create", "agents.send"}
	v2 := base
	v2.Ver = 2
	v2 = v2.Sign(identity)
	empty := Enrollment{V: 1, Device: base.Device, SignPub: phone, BoxPub: seed(3), Ver: 7}.Sign(identity)
	tampered := signed
	tampered.Methods = append([]string{"agents.delete"}, signed.Methods...)
	otherDevice := Enrollment{V: 1, Device: DeviceIDOf(seed(7)), SignPub: phone, BoxPub: seed(3), Methods: []string{"agents.send"}, Reads: []string{}, Ver: 1}.Sign(identity)
	wrongIdentity := ed25519.NewKeyFromSeed(seed(9)).Public().(ed25519.PublicKey)
	cases := []enrollCase{
		mk("valid", signed, identityPub, ""),
		mk("valid, lists written in another order (same signed text)", reordered, identityPub, ""),
		mk("valid, version 2", v2, identityPub, ""),
		mk("valid, empty lists (encoded as arrays, never null)", empty, identityPub, ""),
		mk("invalid, a method added after signing", tampered, identityPub, "signature"),
		mk("invalid, device is not the hash of sign_pub", otherDevice, identityPub, "device binding"),
		mk("invalid, verified under another identity key", signed, wrongIdentity, "signature"),
	}

	link, sign, box := seed(5)[:ClientLinkKeyBytes], seed(6), seed(7)
	binds := []bindCase{}
	add := func(name string, link, sign, box []byte, note string) {
		mac := BindMAC(link, sign, box)
		k := BindKey(link)
		binds = append(binds, bindCase{Name: name, LinkKeyHex: hex.EncodeToString(link), SignPubHex: hex.EncodeToString(sign),
			BoxPubHex: hex.EncodeToString(box), BindKeyHex: hex.EncodeToString(k[:]), MACHex: hex.EncodeToString(mac[:]),
			BindB64URL: base64.RawURLEncoding.EncodeToString(Bind(mac)), Check: CheckDigits(mac), Note: note})
	}
	add("reference", link, sign, box, "")
	add("another sign key", link, seed(8), box, "a relay that substitutes the sign key gets a different bind and check")
	add("another box key", link, sign, seed(8), "a relay that substitutes the box key gets a different bind and check")
	add("another link key", seed(9)[:ClientLinkKeyBytes], sign, box, "without the link key nothing matches")
	add("keys swapped", link, box, sign, "the order of the two keys is part of the text")
	zeros := make([]byte, 32)
	add("all-zero keys", bytes.Repeat([]byte{0}, ClientLinkKeyBytes), zeros, zeros, "")

	ids := []map[string]string{}
	for _, b := range []byte{0, 1, 2, 255} {
		pub := bytes.Repeat([]byte{b}, 32)
		ids = append(ids, map[string]string{"pub_hex": hex.EncodeToString(pub), "device": DeviceIDOf(pub)})
	}
	vectors := map[string]any{
		"version": 1,
		"about":   "known-answer vectors for design sections 3.2, 3.3, 3.4 (authenticated box, revised 2026-11-27), 3.8 and 3.9, generated by Go (internal/clientproto); regenerate with UPDATE_VECTORS=1",
		"signing": "Ed25519 (RFC 8032, deterministic); identity seed is 32 bytes of 0x01, the phone's sign seed 32 bytes of 0x02, box_pub 32 bytes of 0x03; JSON byte fields are standard padded base64",
		"enrollment": map[string]any{
			"label":      "codeaf-enroll-v1\\n",
			"sign_text":  "label + device + \\n + hex(sign_pub) + \\n + hex(box_pub) + \\n + join(sorted(methods),\",\") + \\n + join(sorted(reads),\",\") + \\n + decimal(ver)",
			"sort_order": "byte order of the names (names are ASCII: A-Z a-z 0-9 _ . -)",
			"cases":      cases,
		},
		"bind": map[string]any{
			"k_bind":      "sha256(\"codeaf/link-bind/v1\\n\" || link_key) where link_key is the 16 raw bytes behind the token's 22 characters",
			"mac":         "HMAC-SHA256(k_bind, \"client\\n\" || sign_pub || box_pub), the two keys as raw 32-byte values",
			"bind":        "mac[0:16], base64url without padding, sent as the request's bind",
			"check":       "decimal4( uint16_be(mac[16:18]) mod 10000 ), zero padded; both ends compute it locally and the relay's own check number is never compared",
			"code_length": ClientLinkCodeLen,
			"cases":       binds,
		},
		"device_id": ids,
		"watching_event": map[string]any{
			"frame":            map[string]any{"t": WatchingEventType, "device": base.Device, "on": true, "at": 1700000000000},
			"dampen_ms":        WatchingDampen.Milliseconds(),
			"header":           WatchingHeader,
			"header_for_ms":    WatchingHeaderFor.Milliseconds(),
			"event_off_after":  WatchingEventFor.Milliseconds(),
			"serving_query":    ServingParam + "=1",
			"events_query":     "events=1",
			"phone_wait_max_s": MaxSlotWait,
		},
		"limits": map[string]any{
			"max_slot_bytes": MaxSlotBytes, "max_client_slots": MaxClientSlots, "max_queue_bytes": MaxQueueBytes,
			"max_client_queue": MaxClientQueue, "max_fabric_body": MaxFabricBody, "max_enrollments": MaxEnrollments,
			"max_enroll_names": MaxEnrollNames, "slot_waiters_per_client": SlotWaitersPerClient,
			"slot_waiters_per_identity_worker": SlotWaitersPerIdentity, "slot_waiters_per_relay_go": SlotWaitersPerRelay,
			"max_age_ms": MaxAge.Milliseconds(),
		},
	}
	for k, v := range buildSlotVectors(t) {
		vectors[k] = v
	}
	return vectors
}

// K1: the vectors the TypeScript client is tested against are exactly what Go computes today.
func TestVectorsMatchTheGoldenFile(t *testing.T) {
	got, err := json.MarshalIndent(buildVectors(t), "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	got = append(got, '\n')
	if os.Getenv("UPDATE_VECTORS") == "1" {
		if err := os.MkdirAll(filepath.Dir(goldenPath), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(goldenPath, got, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(goldenPath)
	if err != nil {
		t.Fatalf("no golden vectors; run UPDATE_VECTORS=1 go test ./internal/clientproto: %v", err)
	}
	if !bytes.Equal(got, want) {
		t.Fatal("the vectors changed; if the wire change is intended, run UPDATE_VECTORS=1 go test ./internal/clientproto and tell the mobile unit")
	}
}

// Every vector marked valid verifies and every one marked invalid is refused, so the golden
// file cannot claim a verdict the code disagrees with.
func TestVectorVerdictsAreWhatTheCodeSays(t *testing.T) {
	cases := buildVectors(t)["enrollment"].(map[string]any)["cases"].([]enrollCase)
	for _, c := range cases {
		pub, _ := hex.DecodeString(c.IdentityPub)
		if ok := c.Enrollment.Verify(pub) == nil; ok != c.Valid {
			t.Errorf("%s: verdict %v, vector says %v", c.Name, ok, c.Valid)
		}
	}
}
