// Command compilecatalog emits the engine binding and desk catalog from one
// source. Both outputs are checked in so each consumer can build offline.
package main

import (
	"crypto/sha256"
	"encoding/json"
	"fmt"
	"go/format"
	"log"
	"os"
)

func main() {
	const source = "manifests/kit-v2.json"
	raw, err := os.ReadFile(source)
	if err != nil {
		log.Fatal(err)
	}
	if !json.Valid(raw) {
		log.Fatalf("%s is not JSON", source)
	}
	engine, err := format.Source([]byte(fmt.Sprintf(`// Code generated by go generate. DO NOT EDIT.

package schema

import _ "embed"

//go:embed %s
var kitV2 []byte

const kitV2SourceDigest = "%x"
`, source, sha256.Sum256(raw))))
	if err != nil {
		log.Fatal(err)
	}
	for _, result := range []struct {
		path string
		body []byte
	}{{"kit_v2_generated.go", engine}, {"kit-v2.json", raw}} {
		if err := os.WriteFile(result.path, result.body, 0o644); err != nil {
			log.Fatal(err)
		}
	}
}
