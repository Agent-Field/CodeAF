package main

import (
	"encoding/json"
	"fmt"
	"reflect"
	"sort"
	"strconv"
	"strings"
	"time"

	"github.com/Agent-Field/codeaf/internal/appapi"
)

// The app consumes the registered Go wire, including its JSON nulls. Reflection
// stays in this build tool rather than adding a second codec to the engine.
func typescriptDocument() ([]byte, error) {
	types := make(map[reflect.Type]string)
	owners := make(map[string]reflect.Type)
	for resource, values := range appapi.ContractTypes() {
		for _, value := range values {
			typ := reflect.TypeOf(value)
			if typ == nil || typ.Name() == "" {
				return nil, fmt.Errorf("%s has an unnamed wire type", resource)
			}
			if _, exists := owners[typ.Name()]; exists {
				return nil, fmt.Errorf("duplicate wire type %s", typ.Name())
			}
			types[typ], owners[typ.Name()] = typ.Name(), typ
		}
	}
	g := tsGenerator{types: types}
	var out strings.Builder
	out.WriteString("// Generated by go generate ./internal/appapi. DO NOT EDIT.\n")
	out.WriteString("// Source: registered internal/appapi Go wire types, routes and event payloads.\n")
	out.WriteString("// Times and ids remain strings; optional fields may be absent; required slices/maps may be null.\n\n")
	fmt.Fprintf(&out, "export const APP_CONTRACT = %d as const;\n\n", appapi.Contract)
	out.WriteString("export type JsonValue = null | boolean | number | string | JsonValue[] | { [key: string]: JsonValue };\n\n")
	names := make([]string, 0, len(owners))
	for name := range owners {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		typ := owners[name]
		if typ.Kind() == reflect.Struct && typ.NumField() > 0 {
			fields, err := g.fields(typ)
			if err != nil {
				return nil, fmt.Errorf("%s: %w", name, err)
			}
			fmt.Fprintf(&out, "export interface %s {\n%s}\n\n", name, fields)
		} else {
			definition, err := g.value(typ, "", false, true)
			if err != nil {
				return nil, fmt.Errorf("%s: %w", name, err)
			}
			fmt.Fprintf(&out, "export type %s = %s;\n\n", name, definition)
		}
	}
	out.WriteString("// Canonical method/path templates; request: never means this route has no JSON body.\n")
	out.WriteString("// Responses describe success JSON. SSE and follow modes use AppEvents; errors use AppError.\n")
	out.WriteString("export interface AppRoutes {\n")
	seen := make(map[string]bool)
	for _, route := range appapi.ContractRoutes() {
		key := route.Method + " " + route.Path
		if seen[key] || owners[route.Response] == nil || (route.Request != "" && owners[route.Request] == nil) {
			return nil, fmt.Errorf("invalid route contract %s", key)
		}
		seen[key] = true
		request := route.Request
		if request == "" {
			request = "never"
		}
		fmt.Fprintf(&out, "  %s: { request: %s; response: %s };\n", strconv.Quote(key), request, route.Response)
	}
	out.WriteString("}\n\nexport type AppRoute = keyof AppRoutes;\n")
	out.WriteString("export type AppRequest<R extends AppRoute> = AppRoutes[R][\"request\"];\n")
	out.WriteString("export type AppResponse<R extends AppRoute> = AppRoutes[R][\"response\"];\n")
	out.WriteString("export type AppError = ErrorResponse | ConflictResponse | NotBuiltResponse;\n\n")
	out.WriteString("// Includes transport frames and the separate process.output / ai.* follow streams.\n")
	out.WriteString("export interface AppEvents {\n")
	events := appapi.ContractEvents()
	eventNames := make([]string, 0, len(events))
	for name := range events {
		eventNames = append(eventNames, string(name))
	}
	sort.Strings(eventNames)
	for _, name := range eventNames {
		typ := reflect.TypeOf(events[appapi.EventType(name)])
		if types[typ] == "" {
			return nil, fmt.Errorf("event %s has an unregistered payload", name)
		}
		fmt.Fprintf(&out, "  %s: %s;\n", strconv.Quote(name), types[typ])
	}
	out.WriteString("}\n\nexport type AppEventName = keyof AppEvents;\n")
	out.WriteString("export type AppEvent<N extends AppEventName = AppEventName> = {\n")
	out.WriteString("  [K in N]: { event: K; data: AppEvents[K] }\n}[N];\n")
	return []byte(out.String()), nil
}

type tsGenerator struct {
	types map[reflect.Type]string
}

func (g tsGenerator) fields(typ reflect.Type) (string, error) {
	var out strings.Builder
	seen := make(map[string]bool)
	var visit func(reflect.Type) error
	visit = func(current reflect.Type) error {
		for i := 0; i < current.NumField(); i++ {
			field := current.Field(i)
			if !field.IsExported() {
				continue
			}
			tag := strings.Split(field.Tag.Get("json"), ",")
			name := tag[0]
			if name == "-" {
				continue
			}
			if field.Anonymous && name == "" {
				if field.Type.Kind() != reflect.Struct {
					return fmt.Errorf("unsupported embedded field %s", field.Name)
				}
				if err := visit(field.Type); err != nil {
					return err
				}
				continue
			}
			if name == "" {
				name = field.Name
			}
			optional := false
			for _, option := range tag[1:] {
				if option != "omitempty" {
					return fmt.Errorf("unsupported JSON option %q on %s", option, field.Name)
				}
				optional = true
			}
			if seen[name] {
				return fmt.Errorf("ambiguous JSON field %s", name)
			}
			seen[name] = true
			value, err := g.value(field.Type, field.Tag.Get("jsonschema"), optional, false)
			if err != nil {
				return fmt.Errorf("%s: %w", field.Name, err)
			}
			mark := ""
			if optional {
				mark = "?"
			}
			fmt.Fprintf(&out, "  %s%s: %s;\n", strconv.Quote(name), mark, value)
		}
		return nil
	}
	err := visit(typ)
	return out.String(), err
}

func (g tsGenerator) value(typ reflect.Type, schemaTag string, omitEmpty, definition bool) (string, error) {
	if typ == reflect.TypeOf(time.Time{}) {
		return "string", nil
	}
	if typ == reflect.TypeOf(json.RawMessage{}) {
		return "JsonValue", nil
	}
	if typ.Kind() == reflect.Pointer {
		value, err := g.value(typ.Elem(), schemaTag, false, false)
		if !omitEmpty {
			value += " | null"
		}
		return value, err
	}
	marshaler := reflect.TypeOf((*json.Marshaler)(nil)).Elem()
	if typ.Implements(marshaler) || reflect.PointerTo(typ).Implements(marshaler) {
		return "", fmt.Errorf("custom JSON codec %s needs an explicit TypeScript mapping", typ)
	}
	if !definition && g.types[typ] != "" {
		if omitEmpty && (typ.Kind() == reflect.Slice || typ.Kind() == reflect.Map) {
			return "Exclude<" + g.types[typ] + ", null>", nil
		}
		return g.types[typ], nil
	}
	var enums []string
	for _, part := range strings.Split(schemaTag, ",") {
		if raw, ok := strings.CutPrefix(part, "enum="); ok {
			if typ.Kind() == reflect.String {
				enums = append(enums, strconv.Quote(raw))
			} else {
				if !json.Valid([]byte(raw)) {
					return "", fmt.Errorf("invalid enum %q", raw)
				}
				enums = append(enums, raw)
			}
		}
	}
	if len(enums) > 0 {
		return strings.Join(enums, " | "), nil
	}
	switch typ.Kind() {
	case reflect.String:
		return "string", nil
	case reflect.Bool:
		return "boolean", nil
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64,
		reflect.Float32, reflect.Float64:
		return "number", nil
	case reflect.Slice, reflect.Array:
		if typ.Kind() == reflect.Slice && typ.Elem().Kind() == reflect.Uint8 {
			return "string" + nullable(omitEmpty), nil
		}
		elem, err := g.value(typ.Elem(), "", false, false)
		if err != nil {
			return "", err
		}
		value := "Array<" + elem + ">"
		if typ.Kind() == reflect.Slice {
			value += nullable(omitEmpty)
		}
		return value, nil
	case reflect.Map:
		if typ.Key().Kind() != reflect.String {
			return "", fmt.Errorf("unsupported JSON map key %s", typ.Key())
		}
		elem, err := g.value(typ.Elem(), "", false, false)
		return "Record<string, " + elem + ">" + nullable(omitEmpty), err
	case reflect.Struct:
		if typ.NumField() == 0 {
			return "Record<string, never>", nil
		}
		return "", fmt.Errorf("unregistered wire struct %s", typ)
	case reflect.Interface:
		if typ.NumMethod() == 0 {
			return "JsonValue", nil
		}
	}
	return "", fmt.Errorf("unsupported wire type %s", typ)
}

func nullable(omitEmpty bool) string {
	if omitEmpty {
		return ""
	}
	return " | null"
}
