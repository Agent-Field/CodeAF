// Command schema generates the app's JSON contract without adding reflection dependencies to the binary.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"reflect"
	"sort"

	"github.com/Agent-Field/codeaf/internal/appapi"
	"github.com/invopop/jsonschema"
)

func main() {
	out := flag.String("out", "docs/design/app-v2/schema", "schema output directory")
	typescript := flag.String("typescript", "docs/design/app-v2/wire.ts", "published TypeScript wire types")
	flag.Parse()
	documents, err := schemaDocuments()
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	wire, err := typescriptDocument()
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.MkdirAll(*out, 0755); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	names := make([]string, 0, len(documents))
	for name := range documents {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		if err := os.WriteFile(filepath.Join(*out, name), documents[name], 0644); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
	}
	if err := os.MkdirAll(filepath.Dir(*typescript), 0755); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.WriteFile(*typescript, wire, 0644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func schemaDocuments() (map[string][]byte, error) {
	groups := appapi.ContractTypes()
	owners := make(map[string]string)
	for resource, values := range groups {
		for _, value := range values {
			owners[reflect.TypeOf(value).Name()] = resource
		}
	}
	documents := make(map[string][]byte)
	for resource, values := range groups {
		schema := &jsonschema.Schema{
			Version: jsonschema.Version, Title: "codeaf app " + resource + " contract",
			Comments:    "Generated by go generate ./internal/appapi. Edit the Go wire types, not this file.",
			Definitions: jsonschema.Definitions{}, Extras: map[string]any{},
		}
		for _, value := range values {
			name := reflect.TypeOf(value).Name()
			r := jsonschema.Reflector{Anonymous: true}
			reflected := r.Reflect(value)
			for key, definition := range reflected.Definitions {
				if prior, ok := schema.Definitions[key]; ok {
					a, _ := json.Marshal(prior)
					b, _ := json.Marshal(definition)
					if string(a) != string(b) {
						return nil, fmt.Errorf("%s has inconsistent definition %s", resource, key)
					}
				}
				schema.Definitions[key] = definition
			}
			if _, ok := schema.Definitions[name]; !ok {
				copy := *reflected
				copy.Version, copy.Definitions = "", nil
				schema.Definitions[name] = &copy
			}
			schema.AnyOf = append(schema.AnyOf, &jsonschema.Schema{Ref: "#/$defs/" + name})
		}
		var routes []map[string]string
		for _, route := range appapi.ContractRoutes() {
			if route.Resource != resource {
				continue
			}
			row := map[string]string{"method": route.Method, "path": route.Path, "response": owners[route.Response] + ".json#/$defs/" + route.Response}
			if route.Response == appapi.BinaryResponse {
				row["response"] = "binary"
			}
			if route.Request != "" {
				row["request"] = owners[route.Request] + ".json#/$defs/" + route.Request
			}
			routes = append(routes, row)
		}
		schema.Extras["x-routes"] = routes
		events := make(map[string]string)
		for event, payload := range appapi.ContractEvents() {
			name := reflect.TypeOf(payload).Name()
			if owners[name] == resource {
				events[string(event)] = "#/$defs/" + name
			}
		}
		schema.Extras["x-events"] = events
		encoded, err := json.MarshalIndent(schema, "", "  ")
		if err != nil {
			return nil, err
		}
		documents[resource+".json"] = append(encoded, '\n')
	}
	return documents, nil
}
