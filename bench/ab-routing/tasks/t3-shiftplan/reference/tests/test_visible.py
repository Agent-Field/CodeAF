import pytest

from shiftplan import (
    Interval, Shift, Worker, any_overlap, assign_shifts, load_roster_text,
    payroll, shift_pay_cents, total_minutes, unstaffed,
)


def W(i, rate, *skills):
    return Worker(id=i, name=i.upper(), rate_cents_per_hour=rate,
                  skills=frozenset(skills))


def S(i, date, start, end, skill):
    return Shift(id=i, date=date, window=Interval(start, end),
                 required_skill=skill)


# ---- intervals -------------------------------------------------------------

def test_interval_minutes():
    assert Interval(540, 1020).minutes == 480


def test_interval_rejects_reversed():
    with pytest.raises(ValueError):
        Interval(600, 540)


def test_real_overlap_is_an_overlap():
    assert Interval(540, 720).overlaps(Interval(600, 780))


def test_touching_intervals_do_not_overlap():
    # 09:00-12:00 and 12:00-15:00 are back to back, not overlapping.
    assert not Interval(540, 720).overlaps(Interval(720, 900))


def test_any_overlap_on_touching_run():
    day = [Interval(540, 720), Interval(720, 900), Interval(900, 1080)]
    assert not any_overlap(day)


def test_total_minutes():
    assert total_minutes([Interval(0, 60), Interval(120, 150)]) == 90


# ---- payroll ---------------------------------------------------------------

def test_shift_pay_whole_hour():
    assert shift_pay_cents(2000, 60) == 2000


def test_shift_pay_is_whole_cents():
    # 1795 c/h for 50 minutes is 1495.833... cents; half-up to 1496.
    assert shift_pay_cents(1795, 50) == 1496


def test_payroll_sums_to_whole_cents():
    workers = [W("a", 1795, "till")]
    shifts = [S(f"s{n}", "2026-03-04", 540, 590, "till") for n in range(3)]
    assignments = assign_shifts(shifts, workers, blocked=[])
    totals = payroll(assignments, shifts, workers)
    assert isinstance(totals["a"], int)


# ---- assignment ------------------------------------------------------------

def test_cheapest_qualified_worker_wins():
    workers = [W("a", 2200, "till"), W("b", 1800, "till")]
    shifts = [S("s1", "2026-03-04", 540, 720, "till")]
    assignments = assign_shifts(shifts, workers, blocked=[])
    assert assignments[0].worker_id == "b"


def test_missing_skill_leaves_shift_unstaffed():
    workers = [W("a", 1800, "till")]
    shifts = [S("s1", "2026-03-04", 540, 720, "forklift")]
    assignments = assign_shifts(shifts, workers, blocked=[])
    assert unstaffed(shifts, assignments) == ["s1"]


# ---- loading ---------------------------------------------------------------

def test_load_roster_text_round_trip():
    text = """{"workers": [{"id": "a", "name": "A",
                            "rate_cents_per_hour": 1800, "skills": ["till"]}],
                "shifts": [{"id": "s1", "date": "2026-03-04",
                            "start_minute": 540, "end_minute": 720,
                            "required_skill": "till"}]}"""
    shifts, workers = load_roster_text(text)
    assert len(shifts) == 1 and len(workers) == 1
