// postGraphQL is a POST /graphql carrying body, as a guard sees one.
func postGraphQL(body string) *http.Request {
	r, _ := http.NewRequest(http.MethodPost, "https://api.github.com/graphql", bytes.NewReader([]byte(body)))
	return r
}

// THE WRITE GUARDS PASS ONE KIND OF GraphQL ONLY: a single query operation,
// sent as {"query", "variables"} and nothing else. Everything a mutation could
// hide behind is refused.
func TestGraphQLReadGuardRefusesEverythingButOneQuery(t *testing.T) {
	refused := map[string]string{
		"several operations":   `{"query":"query A{viewer{login}} mutation B{addComment(input:{}){clientMutationId}}","operationName":"B"}`,
		"case-variant key":     `{"query":"mutation{x}","Query":"query{viewer{login}}"}`,
		"leading comment":      "{\"query\":\"# c\\nmutation{x}\"}",
		"array body":           `[{"query":"query{viewer{login}}"}]`,
		"anonymous operation":  `{"query":"{viewer{login}}"}`,
		"two queries":          `{"query":"query{a} query{b}"}`,
		"operationName alone":  `{"query":"query A{viewer{login}}","operationName":"A"}`,
		"subscription":         `{"query":"subscription{x}"}`,
		"unknown extra key":    `{"query":"query{viewer{login}}","extensions":{}}`,
		"duplicate query key":  `{"query":"query{a}","query":"mutation{b}"}`,
		"mutation in the body": `{"query":"query{a} mutation{b}"}`,
		"query then anonymous": `{"query":"query{a} {b}"}`,
		"trailing value":       `{"query":"query{a}"} {"query":"mutation{b}"}`,
		"not JSON":             `query{a}`,
		"no query":             `{"variables":{}}`,
		"unbalanced braces":    `{"query":"query{a"}`,
		"mutation as field":    `{"query":"query{a{mutation}}"}`,
		"block string escape":  `{"query":"query{a(s:\"\"\"x\\\"\"\"y\"\"\")} mutation{b}"}`,
	}
	for name, body := range refused {
		if graphQLRead(postGraphQL(body)) {
			t.Errorf("%s: passed as a read: %s", name, body)
		}
	}
	allowed := map[string]string{
		"named query":           `{"query":"query A{viewer{login}}"}`,
		"variables":             `{"query":"query($o:String!){repository(owner:$o,name:\"x\"){id}}","variables":{"o":"acme"}}`,
		"mutation in a string":  `{"query":"query{search(query:\"mutation\"){issueCount}}"}`,
		"mutation in a comment": "{\"query\":\"query{a # mutation\\n}\"}",
	}
	for name, body := range allowed {
		if !graphQLRead(postGraphQL(body)) {
			t.Errorf("%s: refused: %s", name, body)
		}
	}
	// The product's own request, generated by the product's own code.
	var sent []byte
	forge.OpenIssueCounts(context.Background(), []string{"acme/api", "acme/web"}, func(_ context.Context, payload any) ([]byte, error) {
		sent, _ = json.Marshal(payload)
		return nil, context.Canceled
	})
	if len(sent) == 0 || !graphQLRead(postGraphQL(string(sent))) {
		t.Fatalf("the product's open-issue count was refused: %s", sent)
	}
	// The body is put back for the request to be sent.
	r := postGraphQL(string(sent))
	graphQLRead(r)
	if again, _ := json.Marshal(json.RawMessage(sent)); !bytes.Equal(readAll(t, r), again) {
		t.Fatal("the guard did not put the body back")
	}
}

func readAll(t *testing.T, r *http.Request) []byte {
	t.Helper()
	var b bytes.Buffer
	if _, err := b.ReadFrom(r.Body); err != nil {
		t.Fatal(err)
	}
	return b.Bytes()
}

// graphQLRead is whether r is a POST /graphql that can only READ, for the
// test guards that refuse GitHub writes: the body is one JSON object whose
// keys are exactly "query" and optionally "variables" (case-sensitive, none
// twice, no operationName), and the query is ONE operation that starts with
// the keyword query and names no mutation or subscription anywhere outside a
// string or a comment. The body is put back for the request to be sent.
func graphQLRead(r *http.Request) bool {
	if r.Method != http.MethodPost || r.URL.Path != "/graphql" || r.Body == nil {
		return false
	}
	raw, _ := io.ReadAll(io.LimitReader(r.Body, 1<<20))
	r.Body.Close()
	r.Body = io.NopCloser(bytes.NewReader(raw))
	query, ok := graphQLQueryField(raw)
	return ok && oneQueryOperation(query)
}

// graphQLQueryField reads the body's real keys with the decoder's tokens, so a
// key that differs only in case, or comes twice, cannot hide behind
// encoding/json's case-insensitive, last-one-wins matching.
func graphQLQueryField(raw []byte) (string, bool) {
	dec := json.NewDecoder(bytes.NewReader(raw))
	if t, err := dec.Token(); err != nil || t != json.Delim('{') {
		return "", false
	}
	var query string
	seen := map[string]bool{}
	for dec.More() {
		t, err := dec.Token()
		key, isKey := t.(string)
		if err != nil || !isKey || seen[key] || (key != "query" && key != "variables") {
			return "", false
		}
		seen[key] = true
		if key == "query" {
			err = dec.Decode(&query)
		} else {
			var vars map[string]any
			err = dec.Decode(&vars)
		}
		if err != nil {
			return "", false
		}
	}
	if t, err := dec.Token(); err != nil || t != json.Delim('}') {
		return "", false
	}
	if _, err := dec.Token(); err != io.EOF {
		return "", false
	}
	return query, seen["query"]
}

// oneQueryOperation lexes a GraphQL document: strings ("…" and """…""") and
// # comments are skipped, names are read whole, and braces are counted. It
// holds when there is exactly one top-level operation, introduced by the
// keyword query, and no name mutation or subscription appears at all.
func oneQueryOperation(doc string) bool {
	depth, ops, keyword := 0, 0, false
	for i := 0; i < len(doc); {
		c := doc[i]
		switch {
		case c == '#':
			for i < len(doc) && doc[i] != '\n' {
				i++
			}
		case strings.HasPrefix(doc[i:], `"""`):
			end := blockStringEnd(doc, i+3)
			if end < 0 {
				return false
			}
			i = end
		case c == '"':
			end := stringEnd(doc, i+1)
			if end < 0 {
				return false
			}
			i = end
		case c == '$' || isNameStart(c):
			j := i + 1
			for j < len(doc) && isNamePart(doc[j]) {
				j++
			}
			name := doc[i:j]
			switch {
			case name == "mutation" || name == "subscription":
				return false
			case depth == 0 && name == "query":
				if keyword {
					return false
				}
				keyword, ops = true, ops+1
			case depth == 0 && !keyword:
				// A top-level name outside an operation's head: a fragment, or an
				// operation of another kind.
				return false
			}
			i = j
		case c == '{':
			if depth == 0 {
				if !keyword {
					return false // an anonymous operation
				}
				keyword = false
			}
			depth++
			i++
		case c == '}':
			if depth--; depth < 0 {
				return false
			}
			i++
		default:
			i++
		}
	}
	return depth == 0 && ops == 1 && !keyword
}

// stringEnd is the index after the closing quote of a "…" string whose body
// starts at i, honouring backslash escapes; -1 when it never closes.
func stringEnd(doc string, i int) int {
	for ; i < len(doc); i++ {
		switch doc[i] {
		case '\\':
			i++
		case '"':
			return i + 1
		case '\n':
			return -1
		}
	}
	return -1
}

// blockStringEnd is the index after the closing """ of a block string whose
// body starts at i; \""" inside it is an escaped quote, not the end.
func blockStringEnd(doc string, i int) int {
	for ; i < len(doc); i++ {
		switch {
		case strings.HasPrefix(doc[i:], `\"""`):
			i += 3
		case strings.HasPrefix(doc[i:], `"""`):
			return i + 3
		}
	}
	return -1
}

func isNameStart(c byte) bool {
	return c == '_' || (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z')
}

func isNamePart(c byte) bool { return isNameStart(c) || (c >= '0' && c <= '9') }
